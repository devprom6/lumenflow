import {
  Injectable,
  NotFoundException,
  BadRequestException,
  Logger,
} from '@nestjs/common';
import crypto from 'node:crypto';
import type {
  BridgeQuote,
  BridgeRoute,
  Order,
  QuoteParams,
  TransferStatus,
  UnsignedTransfer,
} from '@lumenflow/shared-types';
import {
  BridgeAdapterRegistry,
  MockBridgeAdapter,
} from '@lumenflow/bridge-adapters';
import { PrismaService } from '../database/prisma.service';
import {
  OrderStateMachineService,
  type InMemoryOrder,
} from '../orders/order-state-machine.service';
import { BridgeSafeguardsService } from './bridge-safeguards.service';

export interface InitiateBridgeTransferResult {
  order: Order;
  transfer: UnsignedTransfer;
}

@Injectable()
export class BridgeService {
  private readonly logger = new Logger(BridgeService.name);
  private readonly registry: BridgeAdapterRegistry;
  private readonly mockAdapter: MockBridgeAdapter;
  private readonly quotesCache = new Map<string, BridgeQuote>();

  constructor(
    private readonly prisma: PrismaService,
    private readonly stateMachine: OrderStateMachineService,
    private readonly safeguards: BridgeSafeguardsService,
  ) {
    this.registry = new BridgeAdapterRegistry();
    this.mockAdapter = new MockBridgeAdapter({ name: 'MockBridge', feePercent: 0.0025 });
    this.registry.register(this.mockAdapter, 10, true);
    this.logger.log('BridgeService initialized with MockBridgeAdapter in BridgeAdapterRegistry');
  }

  public getRegistry(): BridgeAdapterRegistry {
    return this.registry;
  }

  public getMockAdapter(): MockBridgeAdapter {
    return this.mockAdapter;
  }

  public async getSupportedRoutes(): Promise<BridgeRoute[]> {
    const rawRoutes = await this.registry.getSupportedRoutes();
    return rawRoutes.filter((route) => {
      if (this.safeguards.isRouteKilled(route.id)) return false;
      const limits = this.safeguards.getRouteLimit(route.id);
      if (limits) {
        if (limits.minAmount !== undefined && limits.minAmount !== null) route.minAmount = limits.minAmount;
        if (limits.maxAmount !== undefined && limits.maxAmount !== null) route.maxAmount = limits.maxAmount;
      }
      return true;
    });
  }

  public async getQuote(params: QuoteParams): Promise<BridgeQuote> {
    const routeId = `${params.fromChain}-${params.toChain}-${params.fromAsset}`.toLowerCase();
    this.safeguards.assertSafeguards(routeId, 'MockBridge', params.amount);

    const { quote, adapterName } = await this.registry.getQuoteWithFallback(params);
    this.quotesCache.set(quote.id, quote);

    // Save in database if available
    try {
      await this.prisma.quote.create({
        data: {
          id: quote.id,
          sourceAsset: { type: 'token', chain: quote.fromChain, code: quote.fromAsset },
          destinationAsset: { type: 'token', chain: quote.toChain, code: quote.toAsset },
          sourceAmount: quote.fromAmount,
          destinationAmount: quote.toAmount,
          minimumReceived: quote.toAmount,
          slippageTolerance: params.slippageTolerance ?? 0.005,
          priceImpact: 0.001,
          networkFee: quote.fee.amount,
          platformFee: '0',
          path: [quote.fromChain, quote.toChain],
          expiresAt: new Date(quote.expiresAt),
        },
      });
    } catch {
      // In-memory fallback
    }

    this.logger.log(`Bridge quote generated by ${adapterName}: ${quote.id} (${quote.fromChain} -> ${quote.toChain})`);
    return quote;
  }

  public async getQuoteAndAssertNotExpired(quoteId: string): Promise<BridgeQuote> {
    let quote = this.quotesCache.get(quoteId);
    if (!quote) {
      try {
        const dbQuote = await this.prisma.quote.findUnique({ where: { id: quoteId } });
        if (dbQuote) {
          const srcAsset = dbQuote.sourceAsset as { chain?: string; code?: string };
          const dstAsset = dbQuote.destinationAsset as { chain?: string; code?: string };
          quote = {
            id: dbQuote.id,
            provider: 'MockBridge',
            fromChain: srcAsset.chain ?? 'stellar',
            toChain: dstAsset.chain ?? 'ethereum',
            fromAsset: srcAsset.code ?? 'USDC',
            toAsset: dstAsset.code ?? 'USDC',
            fromAmount: dbQuote.sourceAmount,
            toAmount: dbQuote.destinationAmount ?? '0',
            estimatedDurationSeconds: 120,
            fee: {
              amount: dbQuote.networkFee,
              asset: srcAsset.code ?? 'USDC',
            },
            rate: '1.0000',
            createdAt: dbQuote.createdAt.toISOString(),
            expiresAt: dbQuote.expiresAt.toISOString(),
          };
          this.quotesCache.set(quote.id, quote);
        }
      } catch {
        // Offline
      }
    }

    if (!quote) {
      throw new NotFoundException(`Bridge quote with id '${quoteId}' not found.`);
    }

    if (new Date(quote.expiresAt).getTime() <= Date.now()) {
      throw new BadRequestException({
        code: 'QUOTE_EXPIRED',
        message: 'Bridge quote has expired. Please request a new quote.',
        details: { quoteId, expiresAt: quote.expiresAt },
      });
    }

    return quote;
  }

  public async initiateTransfer(
    req: { quoteId: string; sender: string; destinationRecipient?: string | undefined },
    userId = 'guest-user',
  ): Promise<InitiateBridgeTransferResult> {
    const quote = await this.getQuoteAndAssertNotExpired(req.quoteId);
    const routeId = `${quote.fromChain}-${quote.toChain}-${quote.fromAsset}`.toLowerCase();

    // Enforce dynamic safeguards (kill switches and per-route limits)
    this.safeguards.assertSafeguards(routeId, quote.provider, quote.fromAmount);

    const adapter = this.registry.getAdapter(quote.provider);
    if (!adapter) {
      throw new BadRequestException(`Provider '${quote.provider}' not available`);
    }

    // Build unsigned transaction (non-custodial: user signs locally in wallet)
    const transfer = await adapter.buildTransfer(quote, req.sender);

    const orderId = crypto.randomUUID();
    const sourceAsset = { type: 'token', chain: quote.fromChain, code: quote.fromAsset };
    const destinationAsset = { type: 'token', chain: quote.toChain, code: quote.toAsset };

    try {
      await this.prisma.order.create({
        data: {
          id: orderId,
          userId,
          type: 'BRIDGE',
          status: 'CREATED',
          sourceAsset,
          destinationAsset,
          sourceAmount: quote.fromAmount,
          destinationAmount: quote.toAmount,
          quoteId: quote.id,
          externalId: transfer.transferId,
        },
      });

      await this.stateMachine.transition(orderId, 'QUOTED', {
        reason: `Bridge quote ${quote.id} accepted`,
      });
      await this.stateMachine.transition(orderId, 'AWAITING_SIGNATURE', {
        externalId: transfer.transferId,
        reason: 'Unsigned bridge transaction prepared for wallet signing',
      });
    } catch {
      // Memory fallback for tests
      const memOrder: InMemoryOrder = {
        id: orderId,
        userId,
        type: 'BRIDGE',
        status: 'CREATED',
        sourceAsset,
        destinationAsset,
        sourceAmount: quote.fromAmount,
        destinationAmount: quote.toAmount,
        quoteId: quote.id,
        externalId: transfer.transferId,
        createdAt: new Date(),
        updatedAt: new Date(),
        events: [],
      };
      this.stateMachine.setInMemoryOrder(memOrder);

      await this.stateMachine.transition(orderId, 'QUOTED', {
        reason: `Bridge quote ${quote.id} accepted`,
      });
      await this.stateMachine.transition(orderId, 'AWAITING_SIGNATURE', {
        externalId: transfer.transferId,
        reason: 'Unsigned bridge transaction prepared for wallet signing',
      });
    }

    const order = await this.getOrder(orderId);
    return {
      order,
      transfer,
    };
  }

  public async getOrder(orderId: string): Promise<Order> {
    const mem = this.stateMachine.getInMemoryOrder(orderId);
    if (mem) {
      return {
        id: mem.id,
        userId: mem.userId,
        type: mem.type as Order['type'],
        status: mem.status,
        sourceAsset: mem.sourceAsset as Order['sourceAsset'],
        destinationAsset: mem.destinationAsset as Order['destinationAsset'],
        sourceAmount: mem.sourceAmount,
        destinationAmount: mem.destinationAmount,
        quoteId: mem.quoteId,
        stellarTxHash: mem.stellarTxHash,
        externalId: mem.externalId,
        createdAt: mem.createdAt.toISOString(),
        updatedAt: mem.updatedAt.toISOString(),
      };
    }

    try {
      const dbOrder = await this.prisma.order.findUnique({
        where: { id: orderId },
      });

      if (!dbOrder) {
        throw new NotFoundException(`Bridge order with id '${orderId}' not found.`);
      }

      return {
        id: dbOrder.id,
        userId: dbOrder.userId,
        type: dbOrder.type as Order['type'],
        status: dbOrder.status as Order['status'],
        sourceAsset: dbOrder.sourceAsset as unknown as Order['sourceAsset'],
        destinationAsset: dbOrder.destinationAsset as unknown as Order['destinationAsset'],
        sourceAmount: dbOrder.sourceAmount,
        destinationAmount: dbOrder.destinationAmount ?? undefined,
        quoteId: dbOrder.quoteId ?? undefined,
        stellarTxHash: dbOrder.stellarTxHash ?? undefined,
        externalId: dbOrder.externalId ?? undefined,
        createdAt: dbOrder.createdAt.toISOString(),
        updatedAt: dbOrder.updatedAt.toISOString(),
      };
    } catch (err) {
      if (err instanceof NotFoundException) throw err;
      throw new NotFoundException(`Bridge order with id '${orderId}' not found.`);
    }
  }

  public async getTransferStatus(id: string): Promise<{ order: Order; status?: TransferStatus | undefined }> {
    // Check if ID is order ID or transferId
    let order: Order;
    try {
      order = await this.getOrder(id);
    } catch {
      // Look up by externalId
      const memOrders = (this.stateMachine as unknown as { inMemoryOrders?: Map<string, InMemoryOrder> }).inMemoryOrders;
      let matched: InMemoryOrder | undefined;
      if (memOrders) {
        for (const o of memOrders.values()) {
          if (o.externalId === id) {
            matched = o;
            break;
          }
        }
      }

      if (matched) {
        order = await this.getOrder(matched.id);
      } else {
        try {
          const dbOrder = await this.prisma.order.findFirst({
            where: { externalId: id },
          });
          if (!dbOrder) {
            throw new NotFoundException(`Transfer with id '${id}' not found.`);
          }
          order = await this.getOrder(dbOrder.id);
        } catch {
          throw new NotFoundException(`Transfer with id '${id}' not found.`);
        }
      }
    }

    const transferId = order.externalId ?? id;
    let status: TransferStatus | undefined;
    try {
      status = await this.mockAdapter.getStatus(transferId);
    } catch {
      // Status lookup failed or adapter offline
    }

    return {
      order,
      status,
    };
  }
}
